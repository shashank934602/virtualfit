import ASSETS from "./vf-assets.json";

/* ───────────────────────── Types ───────────────────────── */

export type Item = {
  n: string;
  p: number;
  /** colours: [name, hex]. The first colour is the one in the photo. */
  c: [string, string][];
  /** median brightness of the garment in its photo (drives recolouring) */
  lm: number;
  /** sprite-sheet categories: garment background-position (x%, y%) */
  g?: [number, number];
  /** sprite-sheet categories: model background-position-x (%) */
  m?: number;
  /** single-image categories: product photo */
  img?: string;
  /** single-image categories: try-on photo of the model wearing it */
  fit?: string;
};

export type Category = {
  id: string;
  label: string;
  sizes: string[];
  defaultSize: string;
  /** shared sprite sheets (Tops) */
  sheet?: { garm: string; model: string };
  /** shown in place of a product photo that hasn't been generated yet */
  placeholder: string;
  items: Item[];
};

/** Visual layers for a background-image box. */
export type Look = { image: string; size: string; position: string };

