/** Generated by `npm run assets` from the images in assets-src/. */
type AssetEntry = { product?: string; fit?: string; lm?: number };
const GENERATED = ASSETS as Record<string, Record<string, AssetEntry>>;

/** Merge a category's generated photos (if any) into its items. */
function withAssets(id: string, items: Omit<Item, "lm">[], fallbackLm = 0.93): Item[] {
  return items.map((it, i) => {
    const a = GENERATED[id]?.[String(i + 1)] ?? {};
    return { ...it, img: a.product, fit: a.fit, lm: a.lm ?? fallbackLm };
  });
}

